# r2b_facet_forms (and the KT-line solver it pulls in) is needed only by
# bridge(), d6_period_check() and main().  The lattice functions below --
# edge_data, intersection_matrix, root_representatives -- are pure arithmetic,
# and section 6 of paper I uses only those, so the import is made lazily.
from sugrasol.cone import dp3  # noqa: E402

V = np.asarray(dp3().normals)[:, 1:].astype(int)   # (6,2) inward normals = fan rays
CC = 1.0 / 3.0                                     # ell_a = CC + <v_a, s>
N = 6

# --- exact Picard-lattice model of dP3 -------------------------------------
# basis (H, E1, E2, E3), Gram = diag(1,-1,-1,-1).  The six toric boundary curves
# form the hexagon cycle of (-1)-curves; any cyclic identification differs by a
# lattice automorphism, so the invariants below do not depend on the choice.
PIC_GRAM = np.diag([1, -1, -1, -1]).astype(int)
DIVISORS = np.array([                     # D_0 .. D_5, cyclically adjacent
    [0, 1, 0, 0],                         # E1
    [1, -1, -1, 0],                       # H-E1-E2
    [0, 0, 1, 0],                         # E2
    [1, 0, -1, -1],                       # H-E2-E3
    [0, 0, 0, 1],                         # E3
    [1, -1, 0, -1],                       # H-E1-E3
], dtype=int)
ROOTS = np.array([                        # K^perp = A_2 (+) A_1
    [0, 1, -1, 0],                        # alpha_1 = E1-E2
    [0, 0, 1, -1],                        # alpha_2 = E2-E3
    [1, -1, -1, -1],                      # beta    = H-E1-E2-E3
], dtype=int)


def pic_dot(a, b):
    return np.einsum("...i,ij,...j->...", a, PIC_GRAM, b)


def intersection_matrix():
    """Q_ab = D_a . D_b from the exact Picard model (= -1 diag, +1 cyclic)."""
    return pic_dot(DIVISORS[:, None, :], DIVISORS[None, :, :]).astype(float)


def class_periods(c):
    """Reduced periods P_a = c . D_a of an exact Picard class c."""
    return pic_dot(np.atleast_2d(c)[:, None, :], DIVISORS[None, :, :]).squeeze()


# --- polytope combinatorics ------------------------------------------------
def vertices():
    """vert[a] = facet a  ^  facet a+1  (so edge a runs vert[a-1] -> vert[a])."""
    out = np.zeros((N, 2))
    for a in range(N):
        A = np.array([V[a], V[(a + 1) % N]], dtype=float)
        out[a] = np.linalg.solve(A, np.array([-CC, -CC]))
    return out


def _bezout(w):
    """e in Z^2 with <e,w> = 1 (w primitive)."""
    a, b = int(w[0]), int(w[1])
    old_r, r, old_s, s, old_t, t = a, b, 1, 0, 0, 1
    while r:
        q = old_r // r
        old_r, r = r, old_r - q * r
        old_s, s = s, old_s - q * s
        old_t, t = t, old_t - q * t
    assert abs(old_r) == 1, w
    return np.array([old_s, old_t], dtype=int) * old_r


def edge_data():
    """Per facet a: (start vertex, end vertex, primitive tangent w_a, e_a, L_a).

    The orientation is fixed canonically: flipping the edge direction flips both
    w_a and e_a, leaving (*) invariant.  Lattice lengths L_a come out = 1/3, so
    the symplectic form has P_a = 1/3 (the support number), as it must.
    """
    vt = vertices()
    out = []
    for a in range(N):
        p0, p1 = vt[(a - 1) % N], vt[a]
        d = np.rint(3.0 * (p1 - p0)).astype(int)          # denominators are 3
        assert np.allclose(d / 3.0, p1 - p0), d
        g = int(np.gcd(abs(d[0]), abs(d[1])))
        w = d // g
        assert int(V[a] @ w) == 0, (a, V[a], w)           # tangent to facet a
        out.append(dict(p0=p0, p1=p1, w=w, e=_bezout(w), L=g / 3.0))
    return out


# --- the period map on the fitted forms ------------------------------------
def period_matrix(gens, edges=None):
    """(6, K) matrix taking generator coefficients to reduced periods P_a.

    Only the A-type generators (which carry a potential chi_j, tagged in
    r2b_facet_forms.gen_A) contribute; B (ds^ds) and C (dphi^dphi) pull back to
    zero on every divisor.
    """
    edges = edges or edge_data()
    M = np.zeros((N, len(gens)))
    for k, g in enumerate(gens):
        chi, j = getattr(g, "chi", None), getattr(g, "jang", None)
        if chi is None:
            continue
        for a, ed in enumerate(edges):
            dchi = float(chi(ed["p1"])) - float(chi(ed["p0"]))
            M[a, k] = ed["e"][j] * dchi
    return M


def regularity_matrix(gens, edges=None):
    """(6, K) matrix for R_a = <v_a, chi>|_start^end -- must vanish for a smooth
    form (equivalently: the period is independent of the choice of e_a)."""
    edges = edges or edge_data()
    M = np.zeros((N, len(gens)))
    for k, g in enumerate(gens):
        chi, j = getattr(g, "chi", None), getattr(g, "jang", None)
        if chi is None:
            continue
        for a, ed in enumerate(edges):
            dchi = float(chi(ed["p1"])) - float(chi(ed["p0"]))
            M[a, k] = V[a][j] * dchi
    return M


def symplectic_periods():
    """Control: chi_j = s_j is the symplectic form; P_a must be the lattice
    length of edge a (= the support number 1/3 for our hexagon)."""
    edges = edge_data()
    P = np.array([float(ed["e"] @ (ed["p1"] - ed["p0"])) for ed in edges])
    return P, np.array([ed["L"] for ed in edges])


# --- the bridge ------------------------------------------------------------
def bridge(Dh=8, n=20000, seed=5, eps=1e-3, **build_kw):
    """Solve for the three harmonic forms, take their periods, and compare the
    metric intersection form with the period one."""
    import r2b_facet_forms as r2b
    gens = r2b.build(Dh=Dh, **build_kw)
    r = r2b.solve(gens, n=n, seed=seed, eps=eps)
    Pm, Rm = period_matrix(gens), regularity_matrix(gens)
    P = (Pm @ r["coeffs"]).T                              # (3,6) reduced periods
    R = (Rm @ r["coeffs"]).T
    Q = intersection_matrix()
    Qp = np.linalg.pinv(Q)
    I_per = P @ Qp @ P.T
    return dict(r=r, gens=gens, P=P, R=R, Q=Q, Qp=Qp,
                I_metric=r["I"], I_period=I_per)


def root_representatives(P, Q):
    """Real combinations of the three numerical forms whose periods are those of
    the exact roots (alpha_1, alpha_2, beta).  Returns the (3,3) mixing T with
    T @ P = period vectors of ROOTS (solved in the least-squares sense; the
    residual measures how far the numerical span is from K^perp (x) R)."""
    target = np.array([class_periods(c) for c in ROOTS])   # (3,6) exact integers
    T, *_ = np.linalg.lstsq(P.T, target.T, rcond=None)
    T = T.T
    resid = np.linalg.norm(T @ P - target) / np.linalg.norm(target)
    return T, target, resid


def hexagon_rotation():
    """Exact integer matrix of the order-6 hexagon rotation sigma: D_a -> D_{a+1}
    on Pic(dP3), together with its restriction to the root basis of K^perp.

    sigma fixes K, so it preserves K^perp; its isotypic decomposition there is
    canonical and it is exactly the A_2 (+) A_1 splitting: the eigenvalue -1
    ("sign" irrep) eigenvector is the A_1 root beta = H-E1-E2-E3 with
    beta.beta = -2, and the e^{+-2pi i/3} pair spans the A_2 factor.
    """
    S = np.rint(np.linalg.lstsq(DIVISORS.astype(float),
                                np.roll(DIVISORS, -1, axis=0).astype(float),
                                rcond=None)[0].T).astype(int)
    assert all(np.array_equal(S @ DIVISORS[a], DIVISORS[(a + 1) % N])
               for a in range(N))
    Sr = np.rint(np.linalg.lstsq(ROOTS.T.astype(float),
                                 (ROOTS @ S.T).T.astype(float),
                                 rcond=None)[0]).astype(int)
    w, v = np.linalg.eig(Sr.astype(float))
    i = int(np.argmin(np.abs(w + 1)))
    sign_vec = np.real(v[:, i])
    sign_vec = np.rint(sign_vec / np.max(np.abs(sign_vec))).astype(int)
    sign_class = sign_vec @ ROOTS
    return dict(sigma=S, sigma_root=Sr, eigs=w, sign_class=sign_class,
                sign_self=int(pic_dot(sign_class, sign_class)))


def d6_period_check(b):
    """Cross-check the numerically measured D_6 representation on the harmonic
    forms against the exact cyclic shift of their period vectors.

    sigma permutes the facets a -> a+1, so pulling back a form must permute its
    divisor periods the same way.  Comparing the measured 3x3 rep M (r2b) with
    the shift acting on P tests the metric side against pure fan combinatorics.
    """
    import r2b_facet_forms as r2b
    M = r2b.d6_representation(b["r"]["coeffs"], b["gens"])
    P = b["P"]
    best = None
    for sh in (+1, -1):
        for Mx in (M, M.T, np.linalg.inv(M), np.linalg.inv(M).T):
            err = (np.linalg.norm(Mx.T @ P - np.roll(P, sh, axis=1))
                   / np.linalg.norm(P))
            best = err if best is None else min(best, err)
    return M, best


def subspace_angles(P, Q):
    """Principal angles between span(numerical periods) and K^perp (x) R, both
    seen inside the rank-4 row space of Q (with the Q-metric made definite by
    working in the Picard coordinates)."""
    target = np.array([class_periods(c) for c in ROOTS])
    A = np.linalg.qr(P.T)[0]
    B = np.linalg.qr(target.T)[0]
    return np.degrees(np.arccos(np.clip(np.linalg.svd(A.T @ B)[1], -1, 1)))


