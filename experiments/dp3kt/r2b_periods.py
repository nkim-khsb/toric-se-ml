    print(f"    measured D_6 rep vs cyclic shift of the periods: rel error "
          f"{err:.2e}")

    print(f"\n  quantized norm for the cascade rate: for an integral class c,")
    print(f"    ||omega_c||^2_{{L^2}} = -int omega^omega = -c.c  (ASD), so each "
          f"root has ||omega||^2 = 2")
    print(f"    S = (g_s/12) * (-M^T A M)  with A the exact root Gram "
          f"(was: arbitrary L^2 scale ~1/3).")
    return b


