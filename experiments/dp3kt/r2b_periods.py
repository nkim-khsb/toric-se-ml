    print(f"    root Gram (A_2 + A_1) = {G.tolist()}   det {int(round(np.linalg.det(G)))}"
          f"   eigs {np.round(np.linalg.eigvalsh(G.astype(float)), 6)}")

    P_sym, L = symplectic_periods()
    print(f"\n  control (symplectic form, chi_j = s_j):")
    print(f"    periods {np.round(P_sym, 8)}   lattice lengths {np.round(L, 8)}"
          f"   max|diff| {np.max(np.abs(P_sym - L)):.2e}")
    c_sym = np.linalg.pinv(Q) @ P_sym
    print(f"    P^T Q^+ P = {P_sym @ c_sym:.12f}   vs  2*Area(hexagon) = "
          f"{2 * r2b._area():.12f}")

    b = bridge()
    P, R = b["P"], b["R"]
    print(f"\n  harmonic forms: self-dual energies "
          f"{np.array2string(b['r']['lam'][:3], precision=2)}")
    print(f"  reduced periods P_a (rows = the three forms):")
    for i in range(3):
        print(f"    form {i+1}: {np.round(P[i], 6)}   sum {P[i].sum():+.2e}"
              f"   (primitivity: sum_a P_a = 0)")
    print(f"  regularity R_a (must vanish; e_a-ambiguity): "
          f"max {np.max(np.abs(R)):.2e}  rel {np.max(np.abs(R))/np.abs(P).max():.1e}")

    Im, Ip = b["I_metric"], b["I_period"]
    print(f"\n  intersection form, metric side  (int alpha^beta, numerical):")
    print("   ", np.array2string(Im, precision=6, prefix="    "))
    print(f"  intersection form, period side  (P^T Q^+ P, exact functional):")
    print("   ", np.array2string(Ip, precision=6, prefix="    "))
    print(f"  max|difference| {np.max(np.abs(Im - Ip)):.2e}   rel "
          f"{np.max(np.abs(Im - Ip)) / np.max(np.abs(Im)):.2e}")

    T, target, resid = root_representatives(P, Q)
    print(f"\n  integral root representatives (alpha_1, alpha_2, beta):")
    print(f"    period residual |T P - target|/|target| = {resid:.2e}")
    Gm = T @ Im @ T.T
    print(f"    Gram from the METRIC on the root representatives:")
    print("   ", np.array2string(Gm, precision=4, prefix="    "))
    print(f"    exact root Gram: {G.tolist()}")
    print(f"    max|difference| {np.max(np.abs(Gm - G)):.3e}   rel "
          f"{np.max(np.abs(Gm - G)) / 2:.2e}")
    print(f"    eigenvalues: metric {np.round(np.linalg.eigvalsh(Gm), 4)}"
          f"   exact {np.round(np.linalg.eigvalsh(G.astype(float)), 4)}")
    ang = subspace_angles(P, Q)
    print(f"\n  principal angles span(P) vs K^perp (x) R: {np.round(ang, 6)} deg")

    rot = hexagon_rotation()
    print(f"\n  hexagon rotation sigma on K^perp (root basis): "
          f"{rot['sigma_root'].tolist()}  eigs {np.round(rot['eigs'], 4)}")
    print(f"    sign irrep (eig -1) = class {rot['sign_class'].tolist()} in "
          f"(H,E1,E2,E3) = beta = the A_1 factor, self-intersection "
          f"{rot['sign_self']}")
