"""[P1] The period map: divisor periods of the dP3 primitive (1,1) forms.

Closes the "integral / 2-cycle basis" item left open by note sec:o4 and sec:harm,
and supplies the quantized normalization of ||omega||^2 that the cascade rate
S = (g_s/12) M^2 ||omega||^2 needs.

DERIVATION (exact, no integration).  A torus-invariant CLOSED 2-form on a toric
symplectic 4-manifold is (r2b_facet_forms)

    alpha = (d_i chi_j) ds_i ^ dphi_j + B(s) ds1 ^ ds2 + C dphi1 ^ dphi2 .

The toric divisor D_a (preimage of facet a, ell_a = 0) is a 2-sphere swept by the
edge (tangent w_a, <v_a,w_a> = 0) times the circle that survives there (the
circle generated by v_a is the one that collapses).  Pulling back:
ds ^ ds dies (one action direction), dphi ^ dphi dies (one angle direction), and
with dphi_j -> e_a^j dpsi (any e_a with <e_a,w_a> = 1) the survivor is a total
derivative along the edge.  Hence the REDUCED period P_a := (1/2pi) int_{D_a} alpha
is a difference of vertex values,

    P_a = <e_a, chi(V_{a,a+1})> - <e_a, chi(V_{a-1,a})> .                  (*)

The residual freedom e_a -> e_a + c v_a is harmless exactly because smoothness of
alpha at the facet forces <v_a, chi> to be constant along edge a; the size of
    R_a := <v_a, chi(V_{a,a+1})> - <v_a, chi(V_{a-1,a})>
is therefore a derived REGULARITY diagnostic of the numerical form (reported).

Consequences used here (Q = toric intersection matrix of the six boundary curves,
Q^+ its pseudo-inverse; Q has rank 4 = b_2, kernel = the two toric relations):

  (a)  int_X alpha ^ beta = P(alpha)^T Q^+ P(beta)          [period <-> metric]
       (calibrated on the symplectic form itself, chi_j = s_j, P_a = lattice
       length of edge a, both sides = 2 * Area(hexagon) = 2/3.)
  (b)  primitivity <=> sum_a P_a = 0, since -K = sum_a D_a.
  (c)  integral classes = the lattice Q Z^6, i.e. Pic(dP3) = <H,E_1,E_2,E_3>
       with the six D_a the hexagon cycle of (-1)-curves; the primitive lattice
       K^perp is the del Pezzo root lattice A_2 + A_1 (note sec:o4).

The deliverable is the bridge: the three numerically harmonic forms span exactly
K^perp (x) R, and the integral root representatives built from them reproduce the
exact root Gram [[-2,1,0],[1,-2,0],[0,0,-2]] from the METRIC side.

NB (correction to the stated target).  A basis of K^perp cannot have Gram
diag(-2,-2,-3): det = -12 vs det(A_2+A_1) = -6, and the ratio 2 is not a square,
so no sublattice of any index realizes it.  The spectrum {-2,-2,-3} is the set of
negative eigenvalues of the 6x6 circulant Q in the (non-lattice) orthonormal
divisor-coefficient basis -- a presentation, not a lattice invariant, exactly as
note sec:o4 says.  The invariants are (discriminant, signature) = (6, (0,3)).

Sources: rays/normals sugrasol.cone.dp3; Q from the fan (all six boundary curves
are (-1)-curves, cyclically adjacent) = experiments/dp3transition/toric_setup.py;
root lattice conventions = note-o4.md.
"""
